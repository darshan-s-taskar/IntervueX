const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { randomBytes, randomUUID } = require('node:crypto')
const root = path.join(__dirname, '..')
process.env.PUPPETEER_CACHE_DIR = path.join(root, '.cache', 'puppeteer')
const puppeteer = require('../Backend/node_modules/puppeteer')

async function verify() {
    const browser = await puppeteer.launch({ headless: true })
    const errors = []
    try {
        const page = await browser.newPage()
        await page.setViewport({ width: 1440, height: 1000 })
        page.on('pageerror', error => errors.push(error.message))
        const health = await (await fetch('http://localhost:3000/api/health')).json()
        assert.equal(health.database, 'connected')
        const account = { username: 'browser_' + randomUUID(), email: randomUUID() + '@example.invalid', password: randomBytes(24).toString('hex') }
        fs.writeFileSync(path.join(root, '.runtime', 'verification-account.json'), JSON.stringify(account))
        await page.goto('http://localhost:5173', { waitUntil: 'networkidle0' })
        await page.waitForSelector('#email')
        assert.match(page.url(), /\/login$/)
        assert.equal(await page.title(), 'IntervueX')
        await page.type('#email', account.email)
        await page.type('#password', account.password)
        await page.click('button')
        await page.waitForSelector('[role="alert"]')
        assert.match(page.url(), /\/login$/)
        console.log('PASS: Login page loads and rejects invalid credentials visibly.')
        await page.goto('http://localhost:5173/register', { waitUntil: 'networkidle0' })
        await page.waitForSelector('#username')
        await page.type('#username', account.username)
        await page.type('#email', account.email)
        await page.type('#password', account.password)
        await page.click('button')
        await page.waitForSelector('#selfDescription')
        assert.equal(new URL(page.url()).pathname, '/')
        console.log('PASS: Registration signs in and opens the interview form.')
        await page.reload({ waitUntil: 'networkidle0' })
        await page.waitForSelector('#selfDescription')
        console.log('PASS: Authentication survives a browser reload.')
        await page.click('.generate-btn')
        await page.waitForSelector('[role="alert"]')
        assert.match(await page.$eval('[role="alert"]', el => el.textContent), /job description/i)
        await page.type('.panel--left textarea', 'Frontend engineer with JavaScript, React, HTML and CSS skills. Build accessible interfaces and collaborate with a team.')
        await page.type('#selfDescription', 'I am a beginner frontend developer learning JavaScript and React. I have built two small personal websites.')
        if (!health.geminiConfigured || process.argv.includes('--ai')) {
            await page.click('.generate-btn')
            if (!health.geminiConfigured) {
                await page.waitForSelector('[role="alert"]')
                assert.match(await page.$eval('[role="alert"]', el => el.textContent), /GOOGLE_GENAI_API_KEY/)
                console.log('PASS: Missing Gemini configuration displays a useful message without crashing.')
            } else {
                await page.waitForSelector('.interview-page, [role="alert"]', { timeout: 180000 })
                const alert = await page.$('[role="alert"]')
                assert.equal(Boolean(alert), false, 'Live AI request returned an error; inspect the UI and configuration.')
                assert.ok(await page.$('.q-list'))
                console.log('PASS: Live Gemini generation creates and displays an interview report.')
            }
        } else console.log('SKIP: Live Gemini generation (run with --ai to test).')
        await page.screenshot({ path: path.join(root, '.runtime', 'browser-verification.png'), fullPage: true })
        await page.evaluate(async () => {
            const response = await fetch('http://localhost:3000/api/auth/logout', { credentials: 'include' })
            if (!response.ok) throw new Error('Logout failed')
        })
        await page.goto('http://localhost:5173', { waitUntil: 'networkidle0' })
        await page.waitForSelector('#email')
        await page.type('#email', account.email)
        await page.type('#password', account.password)
        await page.click('button')
        await page.waitForSelector('#selfDescription')
        console.log('PASS: Logout and subsequent login work through real browser cookies.')
        assert.deepEqual(errors, [])
        console.log('PASS: No uncaught browser JavaScript errors.')
    } finally { await browser.close() }
}
verify().catch(error => { console.error('FAIL:', error.message); process.exitCode = 1 })
